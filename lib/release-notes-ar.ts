const CATEGORY_TRANSLATIONS_AR: Record<string, string> = {
  "new features": "ميزات جديدة",
  improvements: "تحسينات",
  "bug fixes": "إصلاحات الأخطاء",
  performance: "الأداء",
  security: "الأمان",
  "a note from developer": "رسالة من المطور 💚",
  "a note from developer 💚": "رسالة من المطور 💚",
}

export function translateCategoryToArabic(category: string): string {
  const key = category.trim().toLowerCase()
  return CATEGORY_TRANSLATIONS_AR[key] ?? category
}

